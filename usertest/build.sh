#!/bin/bash
# 在构建机上跑。把 gpu_test.c + vk_test.c 编成 arm64-apple-ios17.0 的可执行文件（lld 的 ad hoc 签名，CodeDirectory 页大小 4 KiB，和 4K 内核对得上），
# 连同 PanVK 的 ICD 库（libvulkan_panfrost.dylib，mesa-build/build-mesa-ios.sh 的产物）一起：
#   1. 读出它们的 cdhash（cdhash.py）；
#   2. 生成 drivers/Mali/gpu_files.inc（内核带着这些文件，boot-arg evb10-exec=1 时写进 Data 卷的 /private/var/evb10，
#      第一个当 init 跑；大的以 zlib 流携带，内核里 uncompress 开）；
#   3. 做 owner trust bundle（uefi-evb10 的 tools/xnu-probe/make-owner-trust-bundle.py：owner 模块带这些 cdhash + 原版两个模块一字节不改）；
#   4. 把 bundle 的 SHA-256 写进 board.toml 的 [payload] trust_cache_sha256（只换第二项，原版那一项不动）。
#
# 一个 cdhash 只信这一份二进制：改了任何一个文件就要重跑这个脚本，再重编内核（文件在内核里）、重打 payload（bundle 在 payload 里）。
#
#   ./build.sh            # 编 + 出 .inc + 出 bundle + 改 board.toml
#   ICD=/path/to.dylib ./build.sh   # 用别处的 ICD 库；ICD=none 不带它（vk_test 会 dlopen 失败，内核 API 部分照常）
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/../env.sh"
ROOT="$MALIMETAL_ROOT"
DEVICE="${DEVICE_DIR:?set DEVICE_DIR (the UniXNU-evb10 checkout) in .env}"
DRIVER="$MALI_DIR"
TOOLS="${UEFI_EVB10_DIR:?set UEFI_EVB10_DIR (the uefi-evb10 checkout) in .env}/tools"
SDK="${SDK:-${IOS_SDK:?set IOS_SDK in .env}}"
A="${LLVM_BIN:?set LLVM_BIN in .env}"
MESA="${MESA:-${MESA_BUILD:?set MESA_BUILD in .env}}"
ICD="${ICD:-$MESA/build/mesa-ios/src/panfrost/vulkan/libvulkan_panfrost.dylib}"
GLSLANG="${GLSLANG:-$MESA/prefix/bin/glslangValidator}"
PY=/usr/bin/python3
OUT="$HERE/out"
mkdir -p "$OUT"
# 内核构建塞进环境的 CCC_OVERRIDE_OPTIONS 会影响所有 clang 调用
unset CCC_OVERRIDE_OPTIONS LLVM_CONFIG CLANG_BIN CC CXX

# 计算着色器 -> SPIR-V（32 位字的十六进制列表，vk_test.c 里 #include）
"$GLSLANG" -V -x -o "$HERE/vk_shader.inc" "$HERE/shaders/square.comp" > /dev/null
"$GLSLANG" -V -x -o "$HERE/vk_tri_vert.inc" "$HERE/shaders/tri.vert" > /dev/null
"$GLSLANG" -V -x -o "$HERE/vk_tri_frag.inc" "$HERE/shaders/tri.frag" > /dev/null

"$A/clang-20" -target arm64-apple-ios17.0 -isysroot "$SDK" -O2 -Wall -Wextra -Werror -I"$DRIVER" -I"$MESA/src/mesa/include" -I"$HERE" \
	-fuse-ld=lld -B"$A" -Wl,-adhoc_codesign gpu_test.c vk_test.c vk_gfx.c -framework IOKit -framework CoreFoundation -o "$OUT/gpu-test" 2> >(grep -v "directory not found" >&2) \
	|| { echo "error: 编译失败" >&2; exit 1; }
"$PY" "$HERE/cdhash.py" "$OUT/gpu-test"

"$A/clang-20" -target arm64-apple-ios17.0 -isysroot "$SDK" -O2 -Wall -Wextra -Werror -dynamiclib -install_name /private/var/evb10/libtiny.dylib \
	-fuse-ld=lld -B"$A" -Wl,-adhoc_codesign tiny.c -o "$OUT/libtiny.dylib" 2> >(grep -v "directory not found" >&2) \
	|| { echo "error: libtiny 编译失败" >&2; exit 1; }
"$PY" "$HERE/cdhash.py" "$OUT/libtiny.dylib"

MACHOS=("$OUT/gpu-test" "$OUT/libtiny.dylib")
FILES=("gpu-test:$OUT/gpu-test" "libtiny.dylib:$OUT/libtiny.dylib")
if [ "$ICD" != none ]; then
	[ -f "$ICD" ] || { echo "error: 没有 ICD 库 $ICD（先跑 mesa-build/build-mesa-ios.sh）" >&2; exit 1; }
	cp "$ICD" "$OUT/libvulkan_panfrost.dylib"
	"$PY" "$HERE/cdhash.py" "$OUT/libvulkan_panfrost.dylib"
	MACHOS+=("$OUT/libvulkan_panfrost.dylib")
	FILES+=("libvulkan_panfrost.dylib:$OUT/libvulkan_panfrost.dylib")
fi

# 插件（metal-plugin/build-plugin.sh 的产物）的可执行文件也进 owner trust bundle；它里面的 ICD 和上面是同一份字节（同一个 cdhash）。
PLUGIN_EXE="${PLUGIN_EXE:-$ROOT/metal-plugin/out/NativeMaliMetal.bundle/NativeMaliMetal}"
if [ -f "$PLUGIN_EXE" ]; then
	PLUGIN_ICD="$(dirname "$PLUGIN_EXE")/libvulkan_panfrost.dylib"
	if [ "$ICD" != none ] && ! cmp -s "$PLUGIN_ICD" "$OUT/libvulkan_panfrost.dylib"; then
		echo "error: 插件 bundle 里的 PanVK 和这里的不是同一份（先重跑 metal-plugin/build-plugin.sh）" >&2
		exit 1
	fi
	MACHOS+=("$PLUGIN_EXE")
fi

"$PY" - "$DRIVER/gpu_files.inc" "${FILES[@]}" <<'EOF'
import hashlib, sys, zlib
out, specs = sys.argv[1], sys.argv[2:]
entries = []
with open(out, 'w') as f:
    f.write('// Generated by usertest/build.sh. Do not edit.\n')
    for i, spec in enumerate(specs):
        name, path = spec.split(':', 1)
        raw = open(path, 'rb').read()
        # 64 KiB and up: carried as a zlib stream (the kernel inflates it with uncompress())
        if len(raw) >= 65536:
            data, rawsize = zlib.compress(raw, 9), len(raw)
        else:
            data, rawsize = raw, 0
        f.write('// %s: %d bytes, sha256 %s%s\n' % (name, len(raw), hashlib.sha256(raw).hexdigest(), ', carried as %d bytes of zlib' % len(data) if rawsize else ''))
        f.write('static const unsigned char kTestFileData%d[] = {\n' % i)
        for k in range(0, len(data), 32):
            f.write(','.join(str(b) for b in data[k:k + 32]) + ',\n')
        f.write('};\n')
        entries.append('  {"%s", kTestFileData%d, sizeof kTestFileData%d, %d},\n' % (name, i, i, rawsize))
        print('%-28s %9d bytes%s' % (name, len(raw), ' -> %d (zlib)' % len(data) if rawsize else ''))
    f.write('static const TestFile kTestFiles[] = {\n' + ''.join(entries) + '};\n')
    f.write('static const unsigned kTestFileCount = %d;\n' % len(entries))
print('wrote', out)
EOF

BUNDLE_OUT="$("$PY" "$TOOLS/xnu-probe/make-owner-trust-bundle.py" "${MACHOS[@]}")"
echo "$BUNDLE_OUT"
SHA="$(echo "$BUNDLE_OUT" | sed -n 's/^sha256 \([0-9a-f]\{64\}\)$/\1/p')"
[ -n "$SHA" ] || { echo "error: bundle 的 SHA-256 没读到" >&2; exit 1; }

"$PY" - "$DEVICE/board.toml" "$SHA" <<'EOF'
import re, sys
path, sha = sys.argv[1:3]
text = open(path).read()
original = '7416ca4f8377146626bb284e2133c76bee6cb4e3ee0af5d648b186235a7323a7'
new = 'trust_cache_sha256 = ["%s", "%s"]' % (original, sha)
pattern = re.compile(r'^trust_cache_sha256 = \[[^\]]*\]$', re.M)
if len(pattern.findall(text)) != 1:
    raise SystemExit('board.toml: expected exactly one trust_cache_sha256 line')
if new in text:
    print('board.toml: pin already current')
else:
    open(path, 'w').write(pattern.sub(new, text))
    print('board.toml: owner bundle pinned (%s…)' % sha[:16])
EOF
